/**
 * Мягкое совпадение выбранных вкусовых признаков с текстом описания.
 * Не заменяет теги в фильтрах — только усиливает score.
 */

/** Корни / фрагменты для поиска в прозе (нижний регистр). */
export const PROSE_STEMS = {
  'Древесно-землистый': ['древесн', 'землист', 'землисто'],
  Минеральный: ['минерал'],
  Освежающий: ['освежающ', 'свежесть', 'свежий', 'прохлад'],
  Ореховый: ['орех'],
  Сливочный: ['сливоч'],
  Карамельный: ['карамел'],
  Сухофруктовый: ['сухофрукт', 'курага', 'чернослив', 'изюм'],
  Фруктовый: ['фрукт', 'ягод', 'яблок', 'абрикос', 'виноград'],
  Цветочный: ['цветоч', 'орхиде', 'цветк'],
  Медовый: ['медов', 'мёд', 'мед '],
  Шоколадный: ['шоколад', 'какао'],
  Мягкий: ['мягк', 'шелковист', 'нежн'],
  Плотный: ['плотн', 'насыщенн', 'густ'],
  Спокойный: ['спокойн', 'уравновеш'],
  Терпкий: ['терпк', 'вяжущ'],
  Яркий: ['ярк', 'звонк', 'выраженн'],
}

/**
 * Собирает поисковый текст карточки: вкус + аромат + описание + эффект.
 */
export function buildTeaProseText(tea) {
  const chunks = [
    ...(tea?.taste || []),
    ...(tea?.aroma || []),
    tea?.description || '',
    tea?.effectDescription || '',
    tea?.brewingGuide || '',
  ]

  return chunks
    .filter(Boolean)
    .join(' ')
    .toLowerCase()
    .replace(/\s+/g, ' ')
}

/**
 * Есть ли признак (тег фильтра) в прозе чая.
 */
export function proseMentionsLabel(proseText, label) {
  if (!proseText || !label) return false

  const stems = PROSE_STEMS[label]
  if (stems?.length) {
    return stems.some((stem) => proseText.includes(stem))
  }

  // fallback: само слово целиком в нижнем регистре
  return proseText.includes(String(label).toLowerCase())
}
